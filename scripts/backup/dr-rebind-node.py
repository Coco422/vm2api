#!/usr/bin/env python3
"""Run on control only for a retired/dead worker. Preserve node/VM IDs, accounts and proxies."""
from pathlib import Path
import argparse, datetime, hashlib, ipaddress, json, os, re, sqlite3, tempfile, urllib.request

def read_env(path):
    out = {}
    for line in Path(path).read_text().splitlines():
        if '=' in line and not line.lstrip().startswith('#'):
            k, v = line.split('=', 1); out[k.strip()] = v.strip().strip('"').strip("'")
    return out

def clear_runtime(record):
    result = dict(record)
    ephemeral = {'container_id', 'pid', 'ip', 'started_at', 'network', 'network_mode', 'worker_socket', 'kernel_socket', 'worker_run_dir', 'worker_token_file', 'egress', 'egress_container', 'stopped', 'removed'}
    result['runtime'] = {k:v for k,v in (record.get('runtime') or {}).items() if k not in ephemeral}
    result['runtime'].setdefault('type', record.get('runtime_type') or 'docker')
    return result

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', default='/opt/vm2api', type=Path)
    parser.add_argument('--node-id', required=True)
    parser.add_argument('--host', required=True)
    parser.add_argument('--expected-host-key', required=True)
    parser.add_argument('--host-key-alg', default='ssh-ed25519')
    parser.add_argument('--confirm-rebind', action='store_true')
    parser.add_argument('--confirm-retired-source', action='store_true')
    args = parser.parse_args(); os.umask(0o077)
    if not re.fullmatch(r'node-[a-z0-9-]+', args.node_id): raise ValueError('Invalid node ID')
    if not re.fullmatch(r'SHA256:[A-Za-z0-9+/]{43}', args.expected_host_key): raise ValueError('Verified host key fingerprint is required')
    try: ipaddress.ip_address(args.host)
    except ValueError:
        if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9.-]{0,252}', args.host): raise ValueError('Invalid replacement host')
    env = read_env(args.root / '.env'); key = env.get('VM2API_API_KEY') or env.get('KIN_API_KEY')
    def api(route, body=None):
        req = urllib.request.Request('http://127.0.0.1:8787' + route, data=json.dumps(body).encode() if body is not None else None, headers={'Authorization': 'Bearer ' + key, 'Content-Type': 'application/json'})
        with urllib.request.urlopen(req, timeout=30) as response: result = json.load(response)
        if not result.get('ok'): raise RuntimeError('Control rejected recovery operation')
        return result.get('data', result)
    node = api('/api/panel/cluster/nodes/' + args.node_id)
    files = []
    for path in (args.root / 'vms').glob('*.json'):
        item = json.loads(path.read_text())
        if item.get('node_id') == args.node_id: files.append((path, item))
    plan = {'node_id': args.node_id, 'old_host': node['host'], 'new_host': args.host, 'verified_host_key': args.expected_host_key, 'vm_ids_preserved': [v['id'] for _, v in files], 'accounts_proxies_owners':'unchanged', 'controller_restart':False}
    if not args.confirm_rebind: print(json.dumps({'dry_run':True, **plan})); return
    if node.get('link', {}).get('state') == 'ready' and not args.confirm_retired_source:
        raise ValueError('Original worker is still connected. Confirm it is retired to prevent split-brain')
    backup_root = args.root / 'data/recovery-rollback'; backup_root.mkdir(mode=0o700, exist_ok=True)
    rollback = Path(tempfile.mkdtemp(prefix='worker-', dir=backup_root)); dbpath = args.root / 'data/kin.db'
    with sqlite3.connect('file:' + str(dbpath) + '?mode=ro', uri=True) as db: db.execute('VACUUM INTO ?', (str(rollback / 'kin.db'),))
    for path, value in files: (rollback / path.name).write_text(json.dumps(value, indent=2) + '\n')
    (rollback / 'plan.json').write_text(json.dumps(plan, indent=2) + '\n')
    stamp = datetime.datetime.now(datetime.timezone.utc).isoformat()
    with sqlite3.connect(dbpath, timeout=30) as db:
        cursor = db.execute('UPDATE cluster_nodes SET host=?,host_key_sha256=?,host_key_alg=?,updated_at=? WHERE id=? AND updated_at=?', (args.host,args.expected_host_key,args.host_key_alg,stamp,args.node_id,node['updated_at']))
        if cursor.rowcount != 1: raise RuntimeError('Node changed concurrently; recovery was not applied')
    for path, value in files:
        current = json.loads(path.read_text())
        if current.get('node_id') != args.node_id: raise RuntimeError('Placement changed concurrently')
        # Only obsolete Docker IDs/PIDs/run sockets are regenerated by native startup.
        new = clear_runtime(current); temporary = path.with_suffix('.recovery-new'); temporary.write_text(json.dumps(new, indent=2) + '\n'); temporary.chmod(0o600); temporary.replace(path)
    api('/api/panel/cluster/nodes/' + args.node_id + '/reconnect', {})
    print(json.dumps({'applied':True, 'rollback':str(rollback), **plan}))

if __name__ == '__main__': main()
